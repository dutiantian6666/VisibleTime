import assert from "node:assert/strict";
import { createRequire } from "node:module";
import { fileURLToPath } from "node:url";
const require = createRequire(import.meta.url);
const { chromium } = require(process.env.PLAYWRIGHT_MODULE || "playwright");
const browser = await chromium.launch({ channel: "msedge", headless: true });
const context = await browser.newContext({ viewport: { width: 1360, height: 1100 }, timezoneId: "Asia/Shanghai" });
const page = await context.newPage();
const errors = [];
page.on("pageerror", error => errors.push(error.message));
const getState = () => page.evaluate(() => JSON.parse(localStorage.getItem("visible-time.v1")));
async function addPlan(name, start, end) {
  await page.locator("#calendar-add").click();
  await page.locator("#plan-task").fill(name);
  await page.locator("#plan-start").fill(start);
  await page.locator("#plan-end").fill(end);
  await page.locator('#plan-editor-form [type="submit"]').click();
}
try {
  await page.clock.install({ time: new Date("2026-10-28T14:00:00+08:00") });
  await page.goto(process.env.TEST_URL || "http://127.0.0.1:4175");
  await page.locator('[data-view="calendar"]').click();
  assert.equal(await page.locator("#focus-view").isVisible(), false);
  assert.equal(await page.locator(".calendar-cell").count(), 42);
  await addPlan("阅读与思考", "2026-10-28T09:07", "2026-10-28T09:19");
  assert.equal(await page.locator(".plan-row").count(), 1);
  assert.match(await page.locator(".plan-duration").textContent(), /12 分/);
  assert.equal((await getState()).sessions.length, 0);
  await page.locator('[data-plan-action="edit"]').click();
  await page.locator("#plan-end").fill("2026-10-28T09:20");
  await page.locator('#plan-editor-form [type="submit"]').click();
  assert.match(await page.locator(".plan-duration").textContent(), /13 分/);
  await addPlan("整理笔记", "2026-10-28T09:18", "2026-10-28T09:25");
  assert.equal(await page.locator(".plan-conflict").count(), 2);
  await page.locator('[data-plan-action="start"]').first().click();
  assert.equal(await page.locator("#focus-view").isVisible(), true);
  await page.clock.fastForward(65000);
  await page.locator("#focus-action").click();
  await page.locator('[data-view="calendar"]').click();
  assert.match(await page.locator(".plan-duration").first().textContent(), /累计实际 1 分 5 秒/);
  assert.equal(await page.locator(".actual-row").count(), 1);
  await page.locator('[data-plan-action="complete"]').first().click();
  assert.equal(await page.locator(".plan-row.done").count(), 1);
  await page.locator("#calendar-next").click();
  assert.equal(await page.locator(".plan-row").count(), 0);
  await page.locator("#calendar-today").click();
  assert.equal(await page.locator(".plan-row").count(), 2);
  await page.reload();
  await page.locator('[data-view="calendar"]').click();
  assert.equal(await page.locator(".plan-row").count(), 2);
  assert.equal(await page.locator(".actual-row").count(), 1);
  await page.screenshot({ path: fileURLToPath(new URL("../artifacts/calendar-v1.3.0.png", import.meta.url)), fullPage: true, animations: "disabled" });
  await page.setViewportSize({ width: 390, height: 844 });
  assert.equal(await page.evaluate(() => document.documentElement.scrollWidth > innerWidth), false);
  await page.screenshot({ path: fileURLToPath(new URL("../artifacts/calendar-mobile-v1.3.0.png", import.meta.url)), fullPage: true, animations: "disabled" });
  page.once("dialog", dialog => dialog.accept());
  await page.locator('[data-plan-action="delete"]').first().click();
  assert.equal((await getState()).sessions.length, 1);
  assert.equal((await getState()).sessions[0].planId, undefined);
  assert.equal(await page.locator(".actual-row").count(), 1);
  assert.deepEqual(errors, []);
  console.log("Calendar UI checks passed: minute precision, editing, overlaps, plan-linked timing, completion, month navigation, persistence, desktop/mobile layout, and deletion preserving actual time.");
} finally { await context.close(); await browser.close(); }
